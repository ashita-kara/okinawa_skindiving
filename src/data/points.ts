export type AreaCategory = "南部" | "中部" | "恩納村" | "名護・本部" | "国頭・北部" | "慶良間" | "宮古" | "石垣";

export interface DivePoint {
  id: string;
  name: string;
  /** 五十音ソート用の読み（ひらがな） */
  yomi: string;
  subName?: string;
  area: AreaCategory;
  lat: number;
  lon: number;
  targetDepth: number;      // 基準水深(m)
  openDirection: number;    // 海が開けている方角 (0=北, 90=東, 180=南, 270=西)
  openAngleWidth: number;   // うねりが入る片側許容角
  reefProtection: number;   // リーフ減衰率 (0.0=外洋直結 〜 0.85=イノー内保護)
  hasOuterReef: boolean;    // 干潮時にうねりを遮断するアウターリーフの有無
  reefThresholdCm?: number; // アウターリーフが防波堤として効き始める潮位(cm)。設定ありのポイントはリーフ型として離岸流判定の対象
  /** 底質（砂の舞いやすさ）: rock=岩礁・ドロップオフ / coral_sand=サンゴ砂・リーフ / fine_sand=細かい砂・シルト */
  bottomType: "rock" | "coral_sand" | "fine_sand";
  /** 雨のときの河川・排水・淡水流入の影響度 */
  riverImpact: "none" | "low" | "high";
  /**
   * 複雑リーフ・閉鎖イノーによる海水の滞留度（0.0=外洋直結で即回復 〜 1.0=複雑なリーフ奥で白濁りがすぐには抜けない）
   * 未指定時は hasOuterReef と reefProtection から自動算出
   */
  reefStagnation?: number;
  /**
   * 「クリア」判定をシビアにするか（砂の舞いやすい海岸）。true の場合、直近の波が小さく雨もない
   * ベタ凪の日だけ「💎 クリア」、それ以外は「💧 良好」止まりになる。
   * 未指定時: 本島の砂地ポイント（coral_sand / fine_sand）は true、岩礁や離島（慶良間・宮古・石垣）は false。
   * 砂の舞う海岸に隣接するアウトリーフなど、底質が岩でも本島の岩礁ポイントほど抜けない場所は明示的に true を指定する。
   */
  clarityStrict?: boolean;
  note: string;             // カレント・濁り・地形の固定アドバイス
}

